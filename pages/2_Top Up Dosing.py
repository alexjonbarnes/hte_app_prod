import streamlit as st
import pandas as pd
from datetime import datetime
import os

st.set_page_config(
    page_title = "Top-Up Dosing",
    layout="wide"
)

st.sidebar.header("Top-Up Dosing")
st.sidebar.markdown("""
    Upload the original dosing files generated by Chronos and the script will:\n
    A: Display all dosing jobs in a single table titled **Total Dosing Jobs**.\n
    B: Compile these into total doses of each substance per well in 
    **Actual vs. Target Per Substance Per Well**.\n
    C: Display any overdoses and underdoses across the compiled dosing jobs in **Overdose Per Substance Per Well** and 
    **Underdose Per Substance Per Well**.
""")

dosing_jobs = st.file_uploader(
    "Upload Dosing Job CSVs",
    type=["csv", "xlsx"],
    accept_multiple_files=True
)


# Generates a datetime object from the filename so that files can be ordered
def extract_date(filename):
    # Dosing jobs end in format YYYYMMDD_HHMMSS.xlsx
    name = os.path.splitext(filename.name)[0]

    date_str = "_".join(name.split("_")[-2:])

    return datetime.strptime(date_str, "%Y%m%d_%H%M%S")


if dosing_jobs:

    filenames = [file.name for file in dosing_jobs]
    duplicates = set([name for name in filenames if filenames.count(name) > 1])

    if duplicates:
        st.error(f"Duplicate files detected. Remove duplicate files to continue.")
        st.stop()

    sorted_dosing_jobs = sorted(dosing_jobs, key=extract_date)

    if len(sorted_dosing_jobs) == 0:
        st.stop()

    combined_df = pd.concat([pd.read_excel(file) for file in sorted_dosing_jobs], ignore_index=True)
    combined_df.index = range(1, len(combined_df) + 1)

    st.write("Total Dosing Jobs")
    st.dataframe(combined_df)

    summary_df = (
        combined_df.groupby(
            ["Tray", "Vial", "Substance Name"],
            as_index=False
        )
        .agg({
            "Target Weight (mg)": "first",
            "Actual Weight (mg)": "sum"
        })
    )

    summary_df["Actual - Target (mg)"] = (
        summary_df["Actual Weight (mg)"] - summary_df["Target Weight (mg)"]
    )

    summary_df["% Difference"] = (
    (summary_df["Actual - Target (mg)"] / summary_df["Target Weight (mg)"]) * 100
    )

    summary_df["Outside ± 25%"] = (
        summary_df["% Difference"].apply(
            lambda x: "⚠️🔴️⚠️" if x > 25 else "⚠️🟡⚠️️" if x < -25 else ""
        )
    )

    summary_df.index = range(1, len(summary_df) + 1)

    st.write("Actual vs. Target Per Substance Per Well")
    st.dataframe(summary_df)

    # Show overdoses
    overdose_df = summary_df[
        summary_df["Outside ± 25%"].isin(["⚠️🔴️⚠️"])
    ]
    overdose_df.index = range(1, len(overdose_df) + 1)

    st.write("Overdose Per Substance Per Well")
    st.dataframe(overdose_df)

    # Show underdoses
    underdose_df = summary_df[
        summary_df["Outside ± 25%"].isin(["⚠️🟡⚠️️"])
    ]
    underdose_df.index = range(1, len(underdose_df) + 1)

    st.write("Underdose Per Substance Per Well")
    st.dataframe(underdose_df)
