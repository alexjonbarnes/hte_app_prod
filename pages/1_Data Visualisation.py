import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.patches import Patch
import numpy as np
import seaborn as sns
from datetime import datetime
import io

st.set_page_config(page_title="Data Visualisation")

st.sidebar.header("Data Visualisation")
st.sidebar.markdown("""
    Upload a results file generated by MNova (can be found in the **"ChromRO"** folder and will be named
    **"results.csv"**).

    Use the **Pie Chart** tab to visualise component distributions across the plate.

    Use the **Heatmap** tab to generate ratio or value heatmaps.
""")

cm = 1 / 2.54  # Convert inches to centimetres

results_csv = st.file_uploader(
    label="Upload MNova Results CSV",
    type=["csv"]
)

if results_csv is None:
    st.stop()

csv_df_raw = pd.read_csv(results_csv)
csv_df = csv_df_raw.fillna(0)
well_col = csv_df["Well Position"]

rows = set(x[0] for x in well_col)
cols_set = set(x[1:] for x in well_col)

num_rows = len(rows)
num_cols = len(cols_set)

headings = list(csv_df)

tab1, tab2 = st.tabs(["Pie Chart", "Heatmap"])

# ── TAB 1: Pie Chart ─────────────────────────────────────────────────────────
with tab1:

    st.sidebar.markdown("---")

    compounds_pie = [x for x in headings if "% Area" in x]

    colour_labels = [
        "Product 1", "Product 2", "SM 1", "SM 2",
        "By-product 1", "By-product 2", "By-product 3", "By-product 4",
        "Unknowns"
    ]
    hex_codes = ["#00aa00", "#00ff00", "#feaa11", "#fed9b3", "#fe3319", "#aa0000", "#0000ff", "#00aaff", "#bbbbbb"]

    colour_df = pd.DataFrame({
        "Component": colour_labels,
        "Hex Code": hex_codes,
        "Colour": hex_codes,
    })

    def color_cells(val):
        return f"background-color: {val}; color: transparent;"

    colour_df_styled = colour_df.style.map(color_cells, subset=["Colour"])

    st.write("Standard Colour Key")
    st.dataframe(colour_df_styled, hide_index=True)

    components = st.multiselect(
        "Select Components",
        compounds_pie,
        placeholder=None,
        key="pie_components"
    )

    if len(components) == 0:
        st.info("Select at least one component to continue.")
    else:

        max_per_row = 5
        component_colours = {}

        row_chunks = [components[i:i + max_per_row] for i in range(0, len(components), max_per_row)]

        for row in row_chunks:
            pie_cols = st.columns(max_per_row)
            for i, component in enumerate(row):
                with pie_cols[i]:
                    component_colours[component] = st.color_picker(
                        label="",
                        value="#000000",
                        key=f"pie_colour_{component}",
                    )
                    st.write(component)

        gen_pie_charts = st.button("Generate Pie Charts")

        if gen_pie_charts:

            legend_handles = [
                Patch(facecolor=component_colours[c], edgecolor="k", label=c)
                for c in components
            ]

            legend_fig, legend_ax = plt.subplots(figsize=(6, 1))
            legend_ax.legend(handles=legend_handles, loc="center", ncol=1, frameon=False)
            legend_ax.axis("off")
            st.pyplot(legend_fig)

            fig, axs = plt.subplots(
                num_rows,
                num_cols,
                figsize=(num_cols * cm, num_rows * cm),
            )

            axs = np.atleast_2d(axs)
            counter = 0

            for x in range(num_rows):
                for y in range(num_cols):
                    ax = axs[x, y]
                    if counter < len(csv_df):
                        values = (
                            csv_df.loc[counter, components]
                            .astype(float)
                            .fillna(0)
                            .values
                        )
                        if values.sum() == 0:
                            ax.axis("off")
                        else:
                            ax.pie(
                                values,
                                colors=[component_colours[c] for c in components],
                                startangle=90,
                                counterclock=False,
                                wedgeprops={"edgecolor": "k", "linewidth": 0.5, "linestyle": "solid"}
                            )
                        ax.set_xticks([])
                        ax.set_yticks([])
                        counter += 1
                    else:
                        ax.axis("off")

            fig.subplots_adjust(left=0, right=1, bottom=0, top=1, wspace=0, hspace=0)
            st.pyplot(fig)

            buf = io.BytesIO()
            fig.savefig(buf, dpi=300, bbox_inches="tight", transparent=True, format="png")
            buf.seek(0)

            st.download_button(
                "Download Visualisation",
                buf,
                f"Pie Chart Visualisation {datetime.now().strftime('%Y%m%d_%H%M%S')}.png",
                mime="image/png"
            )

# ── TAB 2: Heatmap ───────────────────────────────────────────────────────────
with tab2:

    compounds_heatmap = [x for x in headings if x.endswith(")")]

    col1, col2 = st.columns(2)

    with col1:
        with st.form(key="ratio_heatmap_form"):
            st.write("Generate Ratio Heatmap")
            compound = st.selectbox("Select Compound", compounds_heatmap, placeholder=None)
            standard = st.selectbox("Select Standard", compounds_heatmap, placeholder=None)
            normalise_ratio = st.checkbox("Normalise", value=False)
            gen_ratio_heatmap = st.form_submit_button("Generate Ratio Heatmap")

    with col2:
        with st.form("value_heatmap_form"):
            st.write("Generate Value Heatmap")
            heatmap_value = st.selectbox("Select Compound", compounds_heatmap, placeholder=None)
            normalise_value = st.checkbox("Normalise", value=False)
            gen_value_heatmap = st.form_submit_button("Generate Value Heatmap")

    def visualise(arr):
        fig_width = (int(num_cols) + 5) * 1.25 * cm
        fig_height = (int(num_rows) + 0.315) * 1.25 * cm

        fig, ax = plt.subplots(figsize=(fig_width, fig_height))

        mask = np.isnan(arr)
        cmap = plt.cm.viridis.copy()
        cmap.set_bad("white")

        annot = np.empty_like(arr, dtype=object)
        annot[~mask] = np.vectorize(lambda x: f"{x:.1f}")(arr[~mask])
        annot[mask] = ""

        sns.heatmap(
            arr,
            annot=annot,
            cmap=cmap,
            mask=mask,
            square=True,
            fmt="",
            xticklabels=False,
            yticklabels=False,
            ax=ax
        )

        plt.tight_layout(pad=0)
        st.pyplot(fig, use_container_width=False)

        buf = io.BytesIO()
        fig.savefig(buf, dpi=300, bbox_inches="tight", transparent=True, format="png")
        buf.seek(0)

        st.download_button(
            "Download Image",
            buf,
            f"Heatmap Visualisation {datetime.now().strftime('%Y%m%d_%H%M%S')}.png",
            mime="image/png"
        )


    if gen_ratio_heatmap:
        st.session_state["heatmap_mode"] = "ratio"
        st.session_state["normalise_ratio"] = normalise_ratio

    if gen_value_heatmap:
        st.session_state["heatmap_mode"] = "value"
        st.session_state["normalise_value"] = normalise_value

    mode = st.session_state.get("heatmap_mode")

    if mode == "ratio":
        compound_values = csv_df_raw[compound].fillna(0)
        standard_values = csv_df_raw[standard].fillna(max(csv_df_raw[standard] * 10))
        ratio = compound_values / (standard_values + 1e-5)
        array = np.reshape(ratio.values, (num_rows, num_cols))
        if st.session_state.get("normalise_ratio"):
            max_val = np.nanmax(array)
            if max_val > 0:
                array = array / max_val
        visualise(array)

    elif mode == "value":
        values = csv_df_raw[heatmap_value].fillna(0)
        array = np.reshape(values.values, (num_rows, num_cols))
        if st.session_state.get("normalise_value"):
            max_val = np.nanmax(array)
            if max_val > 0:
                array = array / max_val
        visualise(array)